/// What: a new secret, `whsec_` + base64 of 32 random bytes. Why: spec ("between 24 and 64 bytes").
/// 2026-11-10, session_012zDydZCZ4AChqhEZ4oVtaP. Touches: the OS random source.
fn generate_secret() -> String {
    let mut bytes = [0u8; 32];
    OsRng.fill_bytes(&mut bytes);
    format!("whsec_{}", STANDARD.encode(bytes))
}

/// What: the HMAC key inside a secret (base64 after `whsec_`, 24-64 bytes). In: secret.
/// Out: key bytes or `InvalidSecret`. 2026-11-10, session_012zDydZCZ4AChqhEZ4oVtaP. Touches: nothing.
fn secret_key(secret: &str) -> Result<Vec<u8>, WebhookError> {
    let key = STANDARD
        .decode(secret.strip_prefix("whsec_").unwrap_or(secret))
        .map_err(|_| WebhookError::InvalidSecret)?;
    if key.len() < 24 || key.len() > 64 {
        return Err(WebhookError::InvalidSecret);
    }
    Ok(key)
}

/// What: the raw HMAC-SHA256 of `msg_id.timestamp.body`. In: secret, id, timestamp, raw body.
/// Out: 32 bytes. Why: spec "the RAW body bytes, never re-serialised" (the old code used a lossy
/// UTF-8 copy). 2026-11-10, session_012zDydZCZ4AChqhEZ4oVtaP. Touches: nothing.
fn raw_signature(secret: &str, msg_id: &str, timestamp: u64, body: &[u8]) -> Result<Vec<u8>, WebhookError> {
    let mut mac = HmacSha256::new_from_slice(&secret_key(secret)?).map_err(|_| WebhookError::InvalidSecret)?;
    mac.update(msg_id.as_bytes());
    mac.update(b".");
    mac.update(timestamp.to_string().as_bytes());
    mac.update(b".");
    mac.update(body);
    Ok(mac.finalize().into_bytes().to_vec())
}

/// What: the signature header value `v1,<base64>`. In: secret, message id, timestamp, raw body.
/// Out: the value, or an error for a malformed secret. Why: spec `sign`.
/// 2026-11-10, session_012zDydZCZ4AChqhEZ4oVtaP. Touches: nothing.
pub fn sign(secret: &str, msg_id: &str, timestamp: u64, body: &[u8]) -> Result<String, Box<dyn Error>> {
    Ok(format!("v1,{}", STANDARD.encode(raw_signature(secret, msg_id, timestamp, body)?)))
}

/// What: compare two byte strings in time independent of where they differ. In: two slices.
/// Out: equal or not. Why: spec "use a constant time comparison". 2026-11-10,
/// session_012zDydZCZ4AChqhEZ4oVtaP. Touches: nothing.
fn constant_time_eq(a: &[u8], b: &[u8]) -> bool {
    if a.len() != b.len() {
        return false;
    }
    a.iter().zip(b.iter()).fold(0u8, |acc, (x, y)| acc | (x ^ y)) == 0
}

/// What: receiver-side check of a delivery. In: secret, headers (`webhook-id`, `webhook-timestamp`,
/// `webhook-signature` holding one or more space-separated `v1,<base64>`), raw body, tolerance.
/// Out: `Ok(true)` when any signature matches; `InvalidHeader`, `TimestampOutOfRange`,
/// `InvalidSecret` or `SignatureMismatch` otherwise. Why: spec `verify`; the old version did not
/// compile. 2026-11-10, session_012zDydZCZ4AChqhEZ4oVtaP. Touches: the clock.
pub fn verify(
    secret: &str,
    headers: &HashMap<String, String>,
    raw_body: &[u8],
    tolerance_seconds: u64,
) -> Result<bool, WebhookError> {
    let header = |name: &str| {
        headers
            .iter()
            .find(|(k, _)| k.eq_ignore_ascii_case(name))
            .map(|(_, v)| v.as_str())
            .ok_or(WebhookError::InvalidHeader)
    };
    let sig_header = header("webhook-signature")?;
    let msg_id = header("webhook-id")?;
    let ts: u64 = header("webhook-timestamp")?.trim().parse().map_err(|_| WebhookError::InvalidHeader)?;
    let now = now_secs();
    if now.abs_diff(ts) > tolerance_seconds {
        return Err(WebhookError::TimestampOutOfRange);
    }
    let expected = raw_signature(secret, msg_id, ts, raw_body)?;
    let mut matched = false;
    for candidate in sig_header.split_whitespace() {
        if let Some(b64) = candidate.strip_prefix("v1,") {
            if let Ok(sig) = STANDARD.decode(b64) {
                // no early exit: every candidate is checked
                matched |= constant_time_eq(&expected, &sig);
            }
        }
    }
    if matched { Ok(true) } else { Err(WebhookError::SignatureMismatch) }
}

/// What: replace an endpoint's secret. In: store, endpoint id. Out: the new secret.
/// Why: spec `rotate_secret`. 2026-11-10, session_012zDydZCZ4AChqhEZ4oVtaP. Touches: the store.
pub fn rotate_secret(store: &dyn Store, endpoint_id: &str) -> Result<String, Box<dyn Error>> {
    let mut endpoint = store.get_endpoint(endpoint_id).ok_or(WebhookError::EndpointNotFound)?;
    let new_secret = generate_secret();
    endpoint.secret = new_secret.clone();
    store.update_endpoint(endpoint)?;
    Ok(new_secret)
}

/// What: is the URL allowed? `https://` with a host, or `http://localhost` / `http://127.0.0.1` for
/// development. Why: spec "URL must be https://". 2026-11-10, session_012zDydZCZ4AChqhEZ4oVtaP.
/// Touches: nothing.
fn url_allowed(url: &str) -> bool {
    let host_of = |rest: &str| rest.split(|c| c == '/' || c == '?' || c == '#').next().unwrap_or("").to_string();
    if let Some(rest) = url.strip_prefix("https://") {
        return !host_of(rest).is_empty();
    }
    if let Some(rest) = url.strip_prefix("http://") {
        let host = host_of(rest);
        let name = host.split(':').next().unwrap_or("");
        return name == "localhost" || name == "127.0.0.1";
    }
    false
}

/// What: register an org's endpoint. In: store, org, URL, event types. Out: (endpoint id, secret);
/// the secret is returned to the caller once. Why: spec `create_endpoint`.
/// 2026-11-10, session_012zDydZCZ4AChqhEZ4oVtaP. Touches: the store, the OS random source.
pub fn create_endpoint(
    store: &dyn Store,
    org_id: &str,
    url: &str,
    event_types: &[String],
) -> Result<(String, String), Box<dyn Error>> {
    if !url_allowed(url) {
        return Err(Box::new(WebhookError::InvalidUrl));
    }
    let id = format!("ep_{}", random_hex(16));
    let secret = generate_secret();
    store.insert_endpoint(Endpoint {
        id: id.clone(),
        org_id: org_id.to_string(),
        url: url.to_string(),
        secret: secret.clone(),
        event_types: event_types.to_vec(),
        active: true,
        failure_count: 0,
        created_at: now_secs(),
    })?;
    Ok((id, secret))
}

/// What: record one message for the org and a pending delivery for each of THAT org's active
/// endpoints subscribed to the event type. In: store, org, event type, payload. Out: message id.
/// Why: spec `send_event` (tenant isolation). 2026-11-10, session_012zDydZCZ4AChqhEZ4oVtaP.
/// Touches: the store.
pub fn send_event(store: &dyn Store, org_id: &str, event_type: &str, payload: Value) -> Result<String, Box<dyn Error>> {
    let now = now_secs();
    let message_id = format!("msg_{}", random_hex(16));
    store.insert_message(Message {
        id: message_id.clone(),
        org_id: org_id.to_string(),
        event_type: event_type.to_string(),
        payload,
        created_at: now,
    })?;
    for ep in store.list_active_endpoints(org_id, event_type) {
        store.create_delivery(Delivery {
            id: format!("dlv_{}", random_hex(16)),
            message_id: message_id.clone(),
            endpoint_id: ep.id,
            attempt: 0,
            status_code: None,
            success: false,
            error: None,
            next_attempt_at: Some(now),
            delivered_at: None,
        })?;
    }
    Ok(message_id)
}

/// What: when to retry after `attempt` failed attempts. In: attempts so far (1-based), now.
/// Out: the time, or `None` once the 7 retries are used. Why: spec schedule.
/// 2026-11-10, session_012zDydZCZ4AChqhEZ4oVtaP. Touches: nothing.
pub fn schedule_next(attempt: i32, now: u64) -> Option<u64> {
    if attempt < 1 {
        return Some(now);
    }
    RETRY_SCHEDULE_SECS.get((attempt - 1) as usize).map(|d| now + d)
}

/// What: POST one delivery through the injected sender and record the outcome. A 2xx response is
/// success (resets the endpoint's failure count); anything else, or a sender error, is a failed
/// attempt with the next retry scheduled; when retries run out the endpoint's consecutive failure
/// count rises and at 5 the endpoint is disabled. The `webhook-id` is always the message id, so it is
/// identical across retries. In: store, delivery id, sender(url, headers, body) -> (status, body).
/// Out: `()`, or an error when the delivery, message or endpoint is missing.
/// Why: spec `deliver`. 2026-11-10, session_012zDydZCZ4AChqhEZ4oVtaP.
/// Touches: the store, the clock, and the network through the sender.
pub fn deliver<F>(store: &dyn Store, delivery_id: &str, sender: F) -> Result<(), Box<dyn Error>>
where
    F: Fn(&str, &HashMap<String, String>, &[u8]) -> Result<(u16, Vec<u8>), Box<dyn Error>>,
{
    let mut delivery = store.get_delivery(delivery_id).ok_or(WebhookError::DeliveryNotFound)?;
    let message = store.get_message(&delivery.message_id).ok_or(WebhookError::MessageNotFound)?;
    let mut endpoint = store.get_endpoint(&delivery.endpoint_id).ok_or(WebhookError::EndpointNotFound)?;
    if endpoint.org_id != message.org_id {
        return Err(Box::new(WebhookError::EndpointNotFound));
    }
    let body = serde_json::to_vec(&message.payload)?;
    let timestamp = now_secs();
    let signature = sign(&endpoint.secret, &message.id, timestamp, &body)?;
    let mut headers = HashMap::new();
    headers.insert("webhook-id".to_string(), message.id.clone());
    headers.insert("webhook-timestamp".to_string(), timestamp.to_string());
    headers.insert("webhook-signature".to_string(), signature);
    headers.insert("Content-Type".to_string(), "application/json".to_string());

    delivery.attempt += 1;
    match sender(&endpoint.url, &headers, &body) {
        Ok((status, _)) if (200..300).contains(&status) => {
            delivery.status_code = Some(status);
            delivery.success = true;
            delivery.error = None;
            delivery.delivered_at = Some(now_secs());
            delivery.next_attempt_at = None;
            endpoint.failure_count = 0;
        }
        outcome => {
            match outcome {
                Ok((status, _)) => {
                    delivery.status_code = Some(status);
                    delivery.error = Some(format!("HTTP {}", status));
                }
                Err(e) => {
                    delivery.status_code = None;
                    delivery.error = Some(e.to_string());
                }
            }
            delivery.success = false;
            delivery.next_attempt_at = schedule_next(delivery.attempt, now_secs());
            if delivery.next_attempt_at.is_none() {
                endpoint.failure_count += 1;
                if endpoint.failure_count >= DISABLE_AFTER_FAILED_MESSAGES {
                    endpoint.active = false;
                }
            }
        }
    }
    store.update_delivery(delivery)?;
    store.update_endpoint(endpoint)?;
    Ok(())
}
